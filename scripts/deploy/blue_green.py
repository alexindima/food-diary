"""Single-host release handover. Invoke only under the deployment flock.

Docker output stays in a private host log, especially Compose's expanded env.
The production entrypoint is deploy.yml; this module never applies migrations.
"""

import argparse
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import time
from urllib.error import HTTPError, URLError
from urllib.parse import urlparse
from urllib.request import HTTPRedirectHandler, ProxyHandler, Request, build_opener


SLOTS = {"blue": ("api", "client-ssr"), "green": ("api-green", "client-ssr-green")}
DEFAULT_PORTS = {"blue": (5000, 4000), "green": (5001, 4001)}
MIGRATION = re.compile(r"\d{14}_[A-Za-z0-9_]+")
PROBE_PORT = 5090
GRACE_SECONDS = 30
DRAIN_SECONDS = 215  # Nginx worker_shutdown_timeout is 210s (video requests: 190s).
HISTORY_SQL = '''SELECT to_regclass('"__EFMigrationsHistory"') IS NOT NULL AS history_exists \\gset
\\if :history_exists
SELECT COALESCE(json_agg("MigrationId" ORDER BY "MigrationId"), '[]'::json) FROM "__EFMigrationsHistory";
\\else
SELECT '[]'::json;
\\endif
'''


class DeploymentError(RuntimeError):
    pass


class NoRedirect(HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        return None


def write_atomic(path, value, mode=0o600):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".next")
    descriptor = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, mode)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(value)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)


def migration_mode(target_output, applied):
    rows = re.findall(r"^(applied|pending)\s+(\d{14}_[A-Za-z0-9_]+)\s*$", target_output, re.MULTILINE)
    target = [identifier for _, identifier in rows]
    if not target or len(target) != len(set(target)):
        raise DeploymentError("Candidate initializer did not return a unique migration inventory.")
    if not isinstance(applied, list) or any(not isinstance(value, str) or not MIGRATION.fullmatch(value) for value in applied):
        raise DeploymentError("Primary database returned an invalid migration history.")
    if len(applied) != len(set(applied)) or set(applied) - set(target):
        raise DeploymentError("Database contains migrations unknown to the candidate; deployment is blocked.")
    # Reject changes between the two read-only observations as well as parser drift.
    if {identifier for state, identifier in rows if state == "applied"} != set(applied):
        raise DeploymentError("Database migration history changed during preflight.")
    if set(applied) != set(sorted(target)[:len(applied)]):
        raise DeploymentError("Database migration history is not a contiguous prefix of the candidate inventory.")
    return "overlap" if applied and set(target) == set(applied) else "maintenance"


def routes(active, ports=DEFAULT_PORTS, affinity=False):
    if active not in SLOTS or set(ports) != set(SLOTS):
        raise DeploymentError("Invalid deployment routing state.")
    blocks = []
    for color, (api_port, ssr_port) in ports.items():
        if any(not isinstance(port, int) or not 1 <= port <= 65535 for port in (api_port, ssr_port)):
            raise DeploymentError("Invalid loopback port.")
        blocks.append(f"upstream fooddiary_api_{color} {{ server 127.0.0.1:{api_port}; }}")
    api_port, ssr_port = ports[active]
    blocks += [f"upstream fooddiary_api {{ server 127.0.0.1:{api_port}; }}",
               f"upstream fooddiary_ssr {{ server 127.0.0.1:{ssr_port}; }}",
               "map $cookie_fd_api_slot $fooddiary_hub_upstream {",
               f"    default fooddiary_api_{active};"]
    if affinity:
        blocks += [f"    fooddiary_api_{color} fooddiary_api_{color};" for color in SLOTS]
    blocks += ["}", "server {", f"    listen 127.0.0.1:{PROBE_PORT};", "    server_name localhost;",
               "    access_log off;",
               "    location = /health/ready { proxy_pass http://fooddiary_api; }",
               "    location = /internal/version { proxy_pass http://fooddiary_api; }",
               "    location = /health/ssr { proxy_pass http://fooddiary_ssr; }", "    location / { return 404; }", "}"]
    return "# Generated by scripts/deploy/blue_green.py; do not upload defaults over active routing.\n" + "\n".join(blocks) + "\n"


class Deployment:
    def __init__(self, root, environment=None):
        self.root = Path(root)
        self.environment = os.environ if environment is None else environment
        self.plan_path = self.root / ".deploy-plan.json"
        self.state_path = self.root / ".deploy-state.json"
        # Existing directory mount makes atomic replace visible inside the running Nginx.
        self.route_path = self.root / "nginx/sites-enabled/00-fooddiary-upstreams.conf"

    def run(self, *arguments, input=None, required=True):
        result = subprocess.run(arguments, cwd=self.root, input=input, capture_output=True, text=True,
                                encoding="utf-8", timeout=240)
        if result.returncode and required:
            log = self.root / ".deploy-command-failure.log"
            write_atomic(log, result.stderr + "\n" + result.stdout)
            raise DeploymentError(f"Deployment command failed ({arguments[0]}, exit {result.returncode}); private details: {log}")
        return result

    def compose(self, *arguments, **kwargs):
        return self.run("docker", "compose", "--profile", "backend", "--profile", "full", *arguments, **kwargs)

    def running(self, service):
        return self.compose("ps", "--status", "running", "--quiet", service).stdout.strip()

    def request(self, url, data=None, headers=None):
        request = Request(url, data=data, headers={"Connection": "close", **(headers or {})})
        try:
            # A probe must validate this loopback target, not a redirect or an
            # environment-configured HTTP proxy serving the previous release.
            with build_opener(ProxyHandler({}), NoRedirect()).open(request, timeout=5) as response:
                return response.status, response.read(4 * 1024 * 1024).decode("utf-8")
        except HTTPError as error:
            with error:
                return error.code, ""

    def wait(self, predicate, seconds, message):
        deadline = time.monotonic() + seconds
        while True:
            try:
                if predicate():
                    return
            except (OSError, URLError, ValueError):
                pass
            if time.monotonic() >= deadline:
                raise DeploymentError(message)
            time.sleep(1)

    def healthy_api(self, port, sha=None, tag=None):
        if self.request(f"http://127.0.0.1:{port}/health/ready") != (200, "Healthy"):
            return False
        status, body = self.request(f"http://127.0.0.1:{port}/internal/version")
        if status != 200:
            return False
        version = json.loads(body)
        if not isinstance(version, dict):
            return False
        return bool(re.fullmatch(r"[0-9a-f]{40}", str(version.get("commitSha", "")))) and (
            sha is None or version.get("commitSha") == sha) and (tag is None or version.get("imageTag") == tag)

    def memory_headroom(self):
        values = dict(re.findall(r"^(MemAvailable|SwapFree):\s+(\d+) kB$", Path("/proc/meminfo").read_text(), re.MULTILINE))
        available, swap = (int(values.get(key, 0)) * 1024 for key in ("MemAvailable", "SwapFree"))
        if available < 256 * 1024 ** 2 or available + swap < 768 * 1024 ** 2:
            raise DeploymentError("Insufficient memory headroom for overlapping API/SSR; active release is unchanged.")

    @staticmethod
    def ports(configuration):
        def comparable(service):
            return {key: value for key, value in configuration["services"][service].items()
                    if key not in ("ports", "profiles")}
        if comparable("api") != comparable("api-green"):
            raise DeploymentError("API slot configurations must agree except for their loopback ports and profiles.")
        blue_ssr, green_ssr = comparable("client-ssr"), comparable("client-ssr-green")
        green_ssr["environment"] = {**green_ssr["environment"], "SSR_API_ORIGIN": blue_ssr["environment"]["SSR_API_ORIGIN"]}
        if "depends_on" in green_ssr:
            green_ssr["depends_on"] = {("api" if key == "api-green" else key): value
                                       for key, value in green_ssr["depends_on"].items()}
        if blue_ssr != green_ssr:
            raise DeploymentError("SSR slot configurations must agree except for their validated API origin, ports and profiles.")
        result = {}
        for color, services in SLOTS.items():
            ports = []
            for service, target in zip(services, (5000, 4000)):
                bindings = [item for item in configuration["services"][service]["ports"] if item["target"] == target]
                if len(bindings) != 1 or bindings[0].get("host_ip") != "127.0.0.1":
                    raise DeploymentError("Deployment slots must publish exactly one IPv4 loopback port per service.")
                ports.append(int(bindings[0]["published"]))
            origin = configuration["services"][services[1]]["environment"]["SSR_API_ORIGIN"]
            if origin != f"http://{services[0]}:5000":
                raise DeploymentError("SSR slot must use its matching API slot.")
            result[color] = ports
        if len({port for pair in result.values() for port in pair} | {PROBE_PORT}) != 5:
            raise DeploymentError("Deployment slot/probe ports must be distinct.")
        return result

    def save(self, plan):
        write_atomic(self.plan_path, json.dumps(plan, indent=2) + "\n")

    def load(self):
        return json.loads(self.plan_path.read_text(encoding="utf-8"))

    def initialize_routing(self):
        if self.route_path.exists():
            return
        if self.state_path.exists():
            raise DeploymentError("Managed routing is missing; recover it before uploading ingress configuration.")
        # Install the legacy blue route before vhosts reference named upstreams,
        # so a failed bootstrap remains restartable with the existing API/SSR.
        write_atomic(self.route_path, routes("blue"), 0o644)

    def plan(self, requested="auto"):
        sha, tag = self.environment.get("DEPLOY_COMMIT_SHA", ""), self.environment.get("DEPLOY_IMAGE_TAG", "")
        contract_sha = self.environment.get("DEPLOY_API_CONTRACT_SHA", "")
        if not re.fullmatch(r"[0-9a-f]{40}", sha) or tag != "sha-" + sha:
            raise DeploymentError("Deployment requires an exact commit SHA and matching image tag.")
        if not re.fullmatch(r"[0-9a-f]{40}", contract_sha):
            raise DeploymentError("Deployment requires the API contract tree fingerprint from the authorized source revision.")
        bootstrap_recovery = None
        if self.plan_path.exists():
            previous = self.load()
            if previous["phase"] == "retiring":
                # Drain already completed. Recheck the exact candidate before
                # idempotently completing an interrupted retirement/state write.
                self.finish()
            elif previous["phase"] != "complete":
                if (previous["mode"] == "maintenance" and previous["phase"] == "api-ready"
                        and previous["previousState"] is None and not self.state_path.exists()
                        and previous["active"] == previous["candidate"] == "blue"):
                    # A verified new API already owns the migrated database.
                    # Only a compatible forward maintenance retry is eligible;
                    # do not restart pre-migration images or claim completion.
                    bootstrap_recovery = previous
                else:
                    self.abort(previous)
        configuration = json.loads(self.run("docker", "compose", "--profile", "*", "config", "--format", "json").stdout)
        ports = self.ports(configuration)
        target = self.compose("run", "-T", "--rm", "--no-deps", "db-init", "list").stdout
        history = self.compose("exec", "-T", "-e", "PGOPTIONS=-c default_transaction_read_only=on", "postgres", "sh", "-c",
                               'exec psql -X -qAt -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" "$POSTGRES_DB"',
                               input=HISTORY_SQL).stdout
        mode = migration_mode(target, json.loads(history))
        if bootstrap_recovery:
            if (mode != "overlap" or bootstrap_recovery["apiContractSha"] != contract_sha
                    or bootstrap_recovery["ports"] != ports
                    or not self.running("api")
                    or not self.healthy_api(ports["blue"][0], bootstrap_recovery["sha"], bootstrap_recovery["tag"])
                    or not self.route_path.exists() or self.route_path.read_text() != routes("blue", ports)):
                raise DeploymentError("Bootstrap forward recovery requires unchanged migrations, contract and routing, and its exact healthy API.")
        previous_state = json.loads(self.state_path.read_text()) if self.state_path.exists() else None
        active = previous_state["active"] if previous_state else "blue"
        if active not in SLOTS:
            raise DeploymentError("Unknown active slot; inspect deployment state.")
        active_api, active_ssr = SLOTS[active]
        running = [service for pair in SLOTS.values() for service in pair if self.running(service)]
        running += [service for service in ("telegram-bot", "job-manager") if self.running(service)]
        healthy = active_api in running and active_ssr in running and self.healthy_api(
            ports[active][0], previous_state["sha"] if previous_state else None)
        if previous_state and not healthy:
            raise DeploymentError("Active release does not match its saved state; recover it before deployment.")
        if previous_state and (not self.route_path.exists() or self.route_path.read_text() != routes(active, ports)):
            raise DeploymentError("Saved slot and routing file disagree; inspect recovery state before deployment.")
        # Bootstrap also installs affinity/draining and the backplane-capable API.
        # An arbitrary legacy image must never be assumed safe to overlap.
        if (requested == "maintenance" or previous_state is None or not healthy or not self.running("nginx")
                or previous_state.get("apiContractSha") != contract_sha):
            mode = "maintenance"
        candidate = ("green" if active == "blue" else "blue") if mode == "overlap" else active
        if mode == "overlap":
            if any(service in running for service in SLOTS[candidate]):
                raise DeploymentError("Inactive slot is unexpectedly running; inspect it before reuse.")
            bot_environment = configuration["services"]["telegram-bot"].get("environment", {})
            bot_origin = next((value for key, value in bot_environment.items() if key.casefold() == "telegrambot__apibaseurl"), None) or "https://fooddiary.club"
            parsed_origin = urlparse(bot_origin)
            if parsed_origin.scheme != "https" or parsed_origin.hostname in ("api", "api-green", "localhost", "127.0.0.1", "::1"):
                raise DeploymentError("Telegram bot must use the stable HTTPS ingress, not an API slot.")
            nginx_id = self.running("nginx")
            actual = self.run("docker", "inspect", "--format", "{{.Image}}", nginx_id).stdout.strip()
            expected = self.run("docker", "image", "inspect", "--format", "{{.Id}}", configuration["services"]["nginx"]["image"]).stdout.strip()
            if actual != expected:
                raise DeploymentError("Nginx image changes require an explicit maintenance deployment.")
            self.memory_headroom()
        plan = dict(schemaVersion=1, mode=mode, active=active, candidate=candidate, ports=ports, sha=sha, tag=tag, apiContractSha=contract_sha,
                    phase="planned", previousState=previous_state,
                    running=running, started=[], workers=[])
        if bootstrap_recovery:
            plan["recoveredFrom"] = bootstrap_recovery
        self.save(plan)
        if not self.route_path.exists():
            write_atomic(self.route_path, routes(active, ports), 0o644)
        return mode

    def start(self, kind):
        plan = self.load()
        if plan["mode"] == "overlap":
            self.memory_headroom()
        service = SLOTS[plan["candidate"]][0 if kind == "api" else 1]
        # Record ownership before starting, so signals/failure cleanup can see it.
        plan["started"] = list(dict.fromkeys([*plan["started"], service]))
        self.save(plan)
        self.compose("up", "-d", "--force-recreate", "--no-deps", service)
        api_port, ssr_port = plan["ports"][plan["candidate"]]
        if kind == "api":
            self.wait(lambda: self.healthy_api(api_port, plan["sha"], plan["tag"]), 180, "Candidate API readiness/revision did not match.")
        else:
            self.wait(lambda: self.request(f"http://127.0.0.1:{ssr_port}/health/ssr")[0] == 200, 45, "Candidate SSR is not ready.")
            if self.request(f"http://127.0.0.1:{ssr_port}/explore", headers={"Host": "fooddiary.club", "X-Forwarded-Proto": "https"})[0] != 200:
                raise DeploymentError("Candidate SSR warmup failed.")
        plan["phase"] = kind + "-ready"
        self.save(plan)

    def workers(self):
        identifier = self.running("nginx")
        if not identifier:
            return []
        output = self.run("docker", "top", identifier, "-eo", "pid,args").stdout
        return [int(row.split()[0]) for row in output.splitlines() if "nginx: worker process" in row]

    def reload(self, plan):
        if not self.running("nginx"):
            if plan["mode"] != "maintenance":
                raise DeploymentError("Nginx disappeared during handover.")
            self.compose("up", "-d", "--no-deps", "nginx")
        elif plan["mode"] == "maintenance":
            self.compose("up", "-d", "--no-deps", "nginx")
        self.compose("exec", "-T", "nginx", "nginx", "-t")
        self.compose("exec", "-T", "nginx", "nginx", "-s", "reload")

    def probe(self, plan, port=PROBE_PORT):
        return self.healthy_api(port, plan["sha"], plan["tag"]) and self.request(f"http://127.0.0.1:{port}/health/ssr")[0] == 200

    def switch(self):
        plan = self.load()
        if plan["phase"] != "ssr-ready":
            raise DeploymentError("Both candidate services must be ready before switching.")
        plan["phase"] = "switching"
        plan["workers"] = self.workers()
        self.save(plan)
        write_atomic(self.route_path, routes(plan["candidate"], plan["ports"], plan["mode"] == "overlap"), 0o644)
        self.reload(plan)
        self.wait(lambda: self.probe(plan), 30, "Nginx did not serve the exact candidate release.")
        plan["phase"], plan["switchedAt"] = "switched", time.time()
        self.save(plan)

    def drain(self, plan):
        deadline = time.monotonic() + DRAIN_SECONDS
        while set(plan["workers"]) & set(self.workers()):
            if time.monotonic() >= deadline:
                # Stop has a further 60s graceful application deadline. Persistent
                # sockets reconnect; never keep two releases alive indefinitely.
                print("Bounded Nginx drain elapsed; retiring old persistent connections.")
                break
            time.sleep(1)

    def finish(self):
        plan = self.load()
        if plan["phase"] not in ("switched", "retiring"):
            raise DeploymentError("Cannot finish a release before successful proxy probes.")
        if not self.probe(plan):
            raise DeploymentError("Candidate is no longer healthy; retirement is blocked.")
        if plan["mode"] == "overlap" and plan["phase"] == "switched":
            remaining = min(GRACE_SECONDS, GRACE_SECONDS - (time.time() - plan["switchedAt"]))
            if remaining > 0:
                time.sleep(remaining)
            plan["workers"] = sorted(set(plan["workers"]) | set(self.workers()))
            self.save(plan)
            write_atomic(self.route_path, routes(plan["candidate"], plan["ports"]), 0o644)
            self.reload(plan)
            self.wait(lambda: self.probe(plan), 30, "Final active-slot proxy probe failed.")
            self.drain(plan)
            plan["phase"] = "retiring"
            self.save(plan)
        if plan["mode"] == "overlap":
            self.compose("stop", "--timeout", "60", *SLOTS[plan["active"]])
        write_atomic(self.state_path, json.dumps(dict(schemaVersion=1, active=plan["candidate"], sha=plan["sha"], tag=plan["tag"], apiContractSha=plan["apiContractSha"]), indent=2) + "\n")
        plan["phase"] = "complete"
        self.save(plan)

    def abort(self, plan=None):
        if plan is None:
            if not self.plan_path.exists():
                return
            plan = self.load()
        if plan["phase"] == "complete":
            return
        if plan["mode"] == "overlap":
            if plan["phase"] == "retiring":
                raise DeploymentError("Retirement was interrupted; candidate remains active. Resume recovery before another deploy.")
            port = plan["ports"][plan["active"]][0]
            if not self.healthy_api(port, plan["previousState"]["sha"] if plan["previousState"] else None):
                raise DeploymentError("Previous API is unavailable; preserve both slots for explicit recovery.")
            if plan["phase"] in ("switching", "switched"):
                plan["workers"] = sorted(set(plan["workers"]) | set(self.workers()))
                write_atomic(self.route_path, routes(plan["active"], plan["ports"]), 0o644)
                self.reload(plan)
                self.wait(lambda: self.healthy_api(PROBE_PORT, plan["previousState"]["sha"] if plan["previousState"] else None),
                          30, "Previous routing could not be restored; preserve both slots.")
                self.drain(plan)
            if plan["started"]:
                self.compose("stop", "--timeout", "60", *plan["started"])
        elif plan["phase"] == "planned":
            # No migration was attempted. Restart only previously running writers.
            writers = [name for name in plan["running"] if name in ("api", "api-green", "telegram-bot", "job-manager")]
            if writers:
                self.compose("start", *writers)
        else:
            raise DeploymentError("A migration may have run; old application images will not be restarted automatically.")
        plan["phase"] = "complete"
        self.save(plan)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("initialize-routing", "plan", "migration-started", "start-api", "start-ssr", "switch", "finish", "abort"))
    parser.add_argument("--root", type=Path, default=Path("/opt/fooddiary"))
    parser.add_argument("--mode", choices=("auto", "maintenance"), default="auto")
    arguments = parser.parse_args()
    deployment = Deployment(arguments.root)
    try:
        if arguments.command == "initialize-routing":
            deployment.initialize_routing()
        elif arguments.command == "plan":
            print(deployment.plan(arguments.mode))
        elif arguments.command == "migration-started":
            plan = deployment.load()
            plan["phase"] = "migration-started"
            deployment.save(plan)
        elif arguments.command.startswith("start-"):
            deployment.start(arguments.command.removeprefix("start-"))
        else:
            getattr(deployment, arguments.command)()
    except (DeploymentError, OSError, ValueError, subprocess.TimeoutExpired) as error:
        print(f"Deployment handover failed: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
