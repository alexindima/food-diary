using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Diagnostics;

namespace FoodDiary.Analyzers.Tests;

[ExcludeFromCodeCoverage]
public sealed class NamespaceQualifiedTypeAnalyzerTests {
    [Theory]
    [InlineData("class C { void M(System.Text.StringBuilder value) { } }", "System.Text.StringBuilder")]
    [InlineData("using System.Text; class C { System.Text.StringBuilder Value; }", "System.Text.StringBuilder")]
    [InlineData("class C { object M() => new System.Text.StringBuilder(); }", "System.Text.StringBuilder")]
    [InlineData("class C { object M() => typeof(System.Text.StringBuilder); }", "System.Text.StringBuilder")]
    [InlineData("class C { string M() => nameof(System.Text.StringBuilder); }", "System.Text.StringBuilder")]
    [InlineData("class C { object M(object value) => (System.Text.StringBuilder)value; }", "System.Text.StringBuilder")]
    [InlineData("[System.Obsolete] class C { }", "System.Obsolete")]
    [InlineData("[System.ObsoleteAttribute] class C { }", "System.ObsoleteAttribute")]
    [InlineData("class C { string M() => System.String.Empty; }", "System.String")]
    [InlineData("class C { bool M(object value) => System.Object.ReferenceEquals(value, null); }", "System.Object")]
    [InlineData("class C { global::System.Text.StringBuilder Value; }", "global::System.Text.StringBuilder")]
    [InlineData("class C { string M() => global::System.String.Empty; }", "global::System.String")]
    [InlineData("namespace N; class C { System.Text.StringBuilder Value; }", "System.Text.StringBuilder")]
    [InlineData("namespace N { class C { System.Text.StringBuilder Value; } }", "System.Text.StringBuilder")]
    [InlineData("namespace N { class Outer { public class Inner { } } } class C { N.Outer.Inner Value; }", "N.Outer")]
    [InlineData("namespace N { class Item { } } class C { N.Item Value; }", "N.Item")]
    [InlineData("namespace N { interface I { } } class C : N.I { }", "N.I")]
    [InlineData("class C { System.Collections.Generic.List<int> Value; }", "System.Collections.Generic.List<int>")]
    public async Task QualifiedTypeReportsOneActionableDiagnosticAsync(string source, string highlighted) {
        Diagnostic diagnostic = Assert.Single(await AnalyzeAsync(source));

        Assert.Multiple(
            () => Assert.Equal(NamespaceQualifiedTypeAnalyzer.DiagnosticId, diagnostic.Id),
            () => Assert.Equal(highlighted, source.Substring(diagnostic.Location.SourceSpan.Start, diagnostic.Location.SourceSpan.Length)),
            () => Assert.Contains("using directive", diagnostic.GetMessage(), StringComparison.Ordinal),
            () => Assert.Contains("using alias", diagnostic.GetMessage(), StringComparison.Ordinal));
    }

    [Theory]
    [InlineData("using System.Text; class C { StringBuilder Value; }")]
    [InlineData("using Builder = System.Text.StringBuilder; class C { Builder Value; }")]
    [InlineData("using Text = System.Text; class C { Text.StringBuilder Value; }")]
    [InlineData("using Root = System; class C { Root.Text.StringBuilder Value; }")]
    [InlineData("using Root = System; class C { string M() => Root.String.Empty; }")]
    [InlineData("using static System.String; class C { string Value = Empty; }")]
    [InlineData("global using System.Text; class C { StringBuilder Value; }")]
    [InlineData("using System.Text; class C { object M() => new StringBuilder().Append(1); }")]
    [InlineData("class Outer { public class Inner { } } class C { Outer.Inner Value; }")]
    [InlineData("class C { C System => this; C Text => this; object M() => System.Text; }")]
    [InlineData("namespace A.B.C { class C { } }")]
    [InlineData("namespace A.B.C; class C { }")]
    [InlineData("class C { string Value = \"System.Text.StringBuilder\"; /* System.Text.StringBuilder */ }")]
    [InlineData("/// <see cref=\"System.Text.StringBuilder\"/>\nclass C { }")]
    [InlineData("// <auto-generated />\nclass C { System.Text.StringBuilder Value; }")]
    [InlineData("#pragma warning disable FD0020 // Deliberate qualification\nclass C { System.Text.StringBuilder Value; }")]
    public async Task ImportsAliasesAndOtherReferencesDoNotReportDiagnosticAsync(string source) {
        Assert.Empty(await AnalyzeAsync(source));
    }

    [Theory]
    [InlineData("Generated.g.cs")]
    [InlineData("Migration.Designer.cs")]
    public async Task GeneratedFileNamesDoNotReportDiagnosticAsync(string path) {
        Assert.Empty(await AnalyzeAsync("class C { System.Text.StringBuilder Value; }", path));
    }

    [Fact]
    public async Task GenericArgumentsAreCheckedIndependentlyAsync() {
        const string source = "class C { System.Collections.Generic.List<System.Text.StringBuilder> Value; }";

        ImmutableArray<Diagnostic> diagnostics = await AnalyzeAsync(source);

        Assert.Equal(2, diagnostics.Length);
    }

    [Fact]
    public async Task ConflictingNamesStillRequireAnImportOrAliasAsync() {
        const string source = "class StringBuilder { } class C { System.Text.StringBuilder Value; }";

        Assert.Single(await AnalyzeAsync(source));
    }

    [Fact]
    public async Task RuleIsDisabledUnlessExplicitlyEnabledAsync() {
        Assert.Empty(await AnalyzeAsync("class C { System.Text.StringBuilder Value; }", enabled: false));
    }

    [Fact]
    public async Task UnresolvedTypesDoNotProduceAdditionalStyleErrorsAsync() {
        Assert.Empty(await AnalyzeAsync("class C { Missing.Namespace.Type Value; }", allowCompilerErrors: true));
    }

    [Fact]
    public async Task ExternAliasesArePreservedAsync() {
        const string source = "extern alias External; class C { External::System.Text.StringBuilder Value; }";

        Assert.Empty(await AnalyzeAsync(source));
    }

    private static async Task<ImmutableArray<Diagnostic>> AnalyzeAsync(string source, string path = "Test.cs", bool enabled = true, bool allowCompilerErrors = false) {
        SyntaxTree syntaxTree = CSharpSyntaxTree.ParseText(source, new CSharpParseOptions(LanguageVersion.CSharp14), path);
        var options = new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary);
        if (enabled) {
            options = options.WithSpecificDiagnosticOptions(new Dictionary<string, ReportDiagnostic>(StringComparer.Ordinal) {
                [NamespaceQualifiedTypeAnalyzer.DiagnosticId] = ReportDiagnostic.Error,
            });
        }

        var compilation = CSharpCompilation.Create(
            "AnalyzerTest",
            [syntaxTree],
            [MetadataReference.CreateFromFile(typeof(object).Assembly.Location,
                MetadataReferenceProperties.Assembly.WithAliases(["global", "External"]))],
            options);

        if (!allowCompilerErrors) {
            Assert.Empty(compilation.GetDiagnostics().Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error));
        }

        return await compilation
            .WithAnalyzers([new NamespaceQualifiedTypeAnalyzer()])
            .GetAnalyzerDiagnosticsAsync()
            .ConfigureAwait(false);
    }
}
